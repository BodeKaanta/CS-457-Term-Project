#!/usr/bin/env python3
"""Generate cml/pente_lab_import.yaml, a CML lab you can import and start.

The lab is the Sprint 4 one-router topology: bk-R1 (IOSv) with
bk-Client1, bk-Client2 and bk-Server (Alpine Linux). The router's startup
configuration is read from cml/R1.cfg, so the router config file and the lab
can never disagree. Run this again after editing R1.cfg.

Usage (from the repository root):
    python tools/build_cml_lab.py

This is a starting point for the lab, not the Sprint 4 deliverable. The
deliverable sprint_4_topology.yaml must be exported from CML after the lab
has run (see cml/LAB_GUIDE.md).
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R1_CFG = ROOT / "cml" / "R1.cfg"
OUT = ROOT / "cml" / "pente_lab_import.yaml"

INITIALS = "bk"
LAB_TITLE = "CS 457 Pente - Sprint 4 one-router topology"

CLIENT_CONFIG = """\
# CML runs this shell script as root when the Alpine node boots.
hostname {name}
# Console login
USERNAME=cisco
PASSWORD=cisco
# Bring the link up. The IP address, gateway and DNS server come from R1's
# DHCP pool ({pool}): run "sudo udhcpc -i eth0" at the console (Sprint 4 2.3).
ip link set eth0 up
"""

SERVER_CONFIG = """\
# CML runs this shell script as root when the Alpine node boots.
hostname {name}
# Console login
USERNAME=cisco
PASSWORD=cisco
# Static address and default gateway for the game server (Sprint 4 2.2).
# Without the default route the server could not answer the other subnets.
ip link set eth0 up
ip addr add 192.168.20.100/24 dev eth0
ip route add default via 192.168.20.1
"""

# (id, label, node_definition, x, y, config, interfaces)
# Interfaces: (id, label, slot or None for loopback)
ROUTER_IFACES = [("i0", "Loopback0", None), ("i1", "GigabitEthernet0/0", 0),
                 ("i2", "GigabitEthernet0/1", 1), ("i3", "GigabitEthernet0/2", 2),
                 ("i4", "GigabitEthernet0/3", 3)]
HOST_IFACES = [("i0", "eth0", 0)]


def router_config() -> str:
    """The part of R1.cfg between the cut lines, plus "end"."""
    lines = R1_CFG.read_text(encoding="utf-8").splitlines()
    cuts = [i for i, line in enumerate(lines) if "cut here" in line]
    if len(cuts) != 2:
        raise SystemExit(f"{R1_CFG} must contain exactly two 'cut here' lines")
    return "\n".join(lines[cuts[0] + 1:cuts[1]] + ["end"]) + "\n"


def block(text: str, indent: int) -> str:
    """A YAML literal block scalar (|-) indented by `indent` spaces."""
    pad = " " * indent
    body = "\n".join(pad + line if line else "" for line in text.rstrip("\n").splitlines())
    return "|-\n" + body


def node(nid: str, label: str, definition: str, x: int, y: int, config: str,
         ifaces: list) -> str:
    out = [f"  - id: {nid}",
           f"    label: {label}",
           f"    node_definition: {definition}",
           f"    x: {x}",
           f"    y: {y}",
           f"    configuration: {block(config, 6)}",
           "    tags: []",
           "    interfaces:"]
    for iid, ilabel, slot in ifaces:
        out.append(f"      - id: {iid}")
        out.append(f"        label: {ilabel}")
        if slot is None:
            out.append("        type: loopback")
        else:
            out.append(f"        slot: {slot}")
            out.append("        type: physical")
    return "\n".join(out)


def link(lid: str, n1: str, i1: str, n2: str, i2: str, label: str) -> str:
    return "\n".join([f"  - id: {lid}", f"    n1: {n1}", f"    i1: {i1}",
                      f"    n2: {n2}", f"    i2: {i2}", f"    label: {label}"])


def build() -> str:
    r1 = f"{INITIALS}-R1"
    c1, c2, srv = f"{INITIALS}-Client1", f"{INITIALS}-Client2", f"{INITIALS}-Server"
    nodes = [
        node("n0", r1, "iosv", 0, 0, router_config(), ROUTER_IFACES),
        node("n1", c1, "alpine", 240, -240,
             CLIENT_CONFIG.format(name=c1, pool="CLIENT1_POOL"), HOST_IFACES),
        node("n2", c2, "alpine", -240, -240,
             CLIENT_CONFIG.format(name=c2, pool="CLIENT2_POOL"), HOST_IFACES),
        node("n3", srv, "alpine", 0, 240, SERVER_CONFIG.format(name=srv), HOST_IFACES),
    ]
    links = [
        link("l0", "n0", "i2", "n1", "i0",
             f"{r1} Gi0/1 <-> {c1} eth0 (Subnet A 192.168.10.0/24)"),
        link("l1", "n0", "i3", "n2", "i0",
             f"{r1} Gi0/2 <-> {c2} eth0 (Subnet B 192.168.11.0/24)"),
        link("l2", "n0", "i4", "n3", "i0",
             f"{r1} Gi0/3 <-> {srv} eth0 (Subnet C 192.168.20.0/24)"),
    ]
    notes = "\n".join([
        f"Subnet A 192.168.10.0/24: {c1} (DHCP CLIENT1_POOL), gateway and DNS 192.168.10.1",
        f"Subnet B 192.168.11.0/24: {c2} (DHCP CLIENT2_POOL), gateway and DNS 192.168.11.1",
        f"Subnet C 192.168.20.0/24: {srv} static 192.168.20.100, gateway 192.168.20.1",
        "DNS on R1: server.kaanta.edu -> 192.168.20.100",
        "Console login for the Alpine nodes: cisco / cisco",
    ])
    return "\n".join([
        "# Generated by tools/build_cml_lab.py from cml/R1.cfg. Import into CML",
        "# (Dashboard > Import), start the lab, then follow cml/LAB_GUIDE.md.",
        "lab:",
        f"  title: {LAB_TITLE}",
        "  description: Sprint 4 - one Cisco IOSv router (R1) serving three subnets "
        "with DHCP and authoritative DNS for server.kaanta.edu",
        f"  notes: {block(notes, 4)}",
        "  version: 0.2.0",
        "nodes:",
        *nodes,
        "links:",
        *links,
        "",
    ])


def main() -> None:
    OUT.write_text(build(), encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
